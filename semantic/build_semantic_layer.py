"""
Exports semantic/semantic_layer.json, the one file the chatbot reads, from the warehouse's validated semantic_* and
ledger_issue tables (written by warehouse/build_warehouse.py) plus the hand-written metadata in warehouse/metadata/.
Run by the build's last stage ("export"); run it by hand only after editing metadata without rebuilding.

Fails (non-zero exit) if a reviewed example query does not run, so the layer can never silently drift from the data.
Also writes semantic/integrity_manifest.json: SHA-256 of the database, this layer and the example library, which
ai_app/tests/test_integrity.py re-checks to prove the chatbot never altered what it reads.

usage:  python semantic/build_semantic_layer.py
"""
from __future__ import annotations

import hashlib
import json
import pathlib
import re
import sqlite3

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
DB = ROOT / "DB" / "rdpr_star.sqlite"
META = ROOT / "warehouse" / "metadata"


def _meta(name: str) -> dict:
    return json.loads((META / name).read_text(encoding="utf-8"))


def main() -> None:
    con = sqlite3.connect(f"file:{DB.as_posix()}?mode=ro", uri=True)
    docs = _meta("semantic_docs.json")
    tables = {}
    for t, group, grain, doc, rows, lo, hi in con.execute("SELECT * FROM semantic_table_doc ORDER BY table_name"):
        cols = {c: {"type": typ, "unit": unit, "additive": None if add is None else bool(add), "doc": cdoc}
                for c, typ, unit, add, cdoc in con.execute(
                    "SELECT column_name, data_type, unit, additive, doc FROM semantic_column_doc WHERE table_name = ? ORDER BY rowid", (t,))}
        tables[t] = {"group": group, "grain": grain, "doc": doc, "row_count": rows, "date_from": lo, "date_to": hi, "columns": cols}
    period = dict(con.execute("SELECT key, value FROM semantic_data_period").fetchall())
    caps = _meta("capability_manifest.json")["capabilities"]
    counts = dict(con.execute("SELECT topic, row_count FROM semantic_capability").fetchall())
    for c in caps:
        c["row_count"] = counts.get(c["topic"], 0)
    caveats = [{"id": i, "caveat": cav, "affects": json.loads(aff)} for i, cav, aff in
               con.execute("SELECT id, caveat, affects FROM ledger_issue ORDER BY id")]

    al = docs["aliases"]
    ents = {
        "zillas": [dict(zip(("id", "name", "total_gps"), r)) for r in con.execute("SELECT zilla_id, zilla_name, total_gps FROM mart_dim_zilla ORDER BY zilla_id")],
        "taluks": [dict(zip(("id", "name", "zilla"), r)) for r in con.execute("SELECT taluk_id, taluk_name, zilla_name FROM mart_dim_taluk ORDER BY taluk_id")],
        "gps": [dict(zip(("id", "name", "taluk", "zilla"), r)) for r in con.execute("SELECT gp_id, gp_name, taluk_name, zilla_name FROM mart_dim_gp ORDER BY gp_id")],
        "fiscal_years": [r[0] for r in con.execute("SELECT fy FROM mart_dim_fy WHERE fy <> '2021-22' ORDER BY fy")],
        "all_fiscal_years": [r[0] for r in con.execute("SELECT fy FROM mart_dim_fy ORDER BY fy")],
        "month_labels": [r[0] for r in con.execute("SELECT month_label FROM mart_dim_month ORDER BY month_id")],
        "schemes": [dict(zip(("id", "name", "category"), r)) for r in con.execute("SELECT scheme_id, scheme_name, scheme_category FROM mart_dim_scheme ORDER BY scheme_id")],
        "fee_types": [dict(zip(("id", "name"), r)) for r in con.execute("SELECT fee_type_id, fee_type_name FROM mart_dim_fee_type ORDER BY fee_type_id")],
        "property_types": [dict(zip(("id", "name", "category"), r)) for r in con.execute("SELECT property_type_id, property_type_name, report_category FROM mart_dim_property_type ORDER BY property_type_id")],
        "staff_types": [dict(zip(("code", "name"), r)) for r in con.execute("SELECT staff_type_code, staff_type_name FROM mart_dim_staff_type ORDER BY staff_type_code")],
        "designations": [r[0] for r in con.execute("SELECT DISTINCT designation_name FROM mart_fact_taluk_staff ORDER BY designation_name")],
        "zilla_aliases": al["zilla"], "scheme_aliases": al["scheme"], "fee_type_aliases": al["fee_type"],
        "property_category_aliases": al["property_category"], "staff_type_aliases": al["staff_type"],
    }
    layer = {
        "_purpose": "Semantic layer for the RDPR Finance / Revenue / HRMS NL2SQL chatbot. Generated by semantic/build_semantic_layer.py "
                    "from the warehouse's semantic_* tables; do not edit by hand. The chatbot reads it; it never writes.",
        "database": "DB/rdpr_star.sqlite (SQLite). The chatbot's SQL may read only mart_* tables.",
        "data_period": {**period, "data_nature": docs["data_period"]["data_nature"]},
        "rules": docs["rules"], "glossary": docs["glossary"], "metrics": _meta("metric_registry.json")["metrics"],
        "non_averageable_columns": docs["non_averageable_columns"], "non_summable_columns": docs["non_summable_columns"],
        "tables": tables, "capabilities": caps, "caveats": caveats, "entities": ents,
    }

    ex_path = HERE / "example_queries.sql"
    n_ex = 0
    for b in re.split(r"\n(?=-- \d+\. )", ex_path.read_text(encoding="utf-8")):
        m = re.match(r"-- (\d+)\. (.*)\n", b)
        if not m:
            continue
        sql = b[m.end():].strip().rstrip(";")
        try:
            if not con.execute(sql).fetchmany(5):
                raise SystemExit(f"example {m.group(1)} returns no rows:\n{sql}")
        except sqlite3.Error as exc:
            raise SystemExit(f"example {m.group(1)} fails: {exc}\n{sql}")
        n_ex += 1
    con.close()

    text = json.dumps(layer, indent=1, ensure_ascii=False)
    (HERE / "semantic_layer.json").write_text(text, encoding="utf8")

    def sha(p: pathlib.Path) -> str:
        h = hashlib.sha256()
        with open(p, "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):
                h.update(chunk)
        return h.hexdigest()
    manifest = {"_purpose": "SHA-256 of the files the chatbot only reads; written by semantic/build_semantic_layer.py. "
                            "ai_app/tests/test_integrity.py re-hashes them.",
                "files": {p.resolve().relative_to(ROOT.resolve()).as_posix(): sha(p) for p in (DB, HERE / "semantic_layer.json", ex_path)}}
    (HERE / "integrity_manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf8")
    print(f"wrote semantic_layer.json: {len(tables)} tables, {len(layer['metrics'])} metrics, {n_ex} examples, "
          f"{len(layer['glossary'])} glossary terms, sha256 {hashlib.sha256(text.encode()).hexdigest()[:12]}")


if __name__ == "__main__":
    main()
